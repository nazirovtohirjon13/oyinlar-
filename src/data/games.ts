export function getPlayerLevel(totalPoints: number): { level: number; title: string; nextLevelPoints: number; progressPct: number } {
  const levels = [
    { min: 0, title: 'Yangi kashfiyotchi' },
    { min: 300, title: 'Bilimdon' },
    { min: 800, title: 'Zehn ustasi' },
    { min: 1500, title: '3D Strateg' },
    { min: 2500, title: 'Olim' },
    { min: 4000, title: 'Buyuk Zehn' },
  ];
  let idx = 0;
  for (let i = levels.length - 1; i >= 0; i--) {
    if (totalPoints >= levels[i].min) {
      idx = i;
      break;
    }
  }
  const currentMin = levels[idx].min;
  const nextMin = levels[idx + 1]?.min ?? currentMin + 2000;
  const pct = Math.min(100, Math.round(((totalPoints - currentMin) / (nextMin - currentMin)) * 100));
  return {
    level: idx + 1,
    title: levels[idx].title,
    nextLevelPoints: nextMin,
    progressPct: pct,
  };
}
